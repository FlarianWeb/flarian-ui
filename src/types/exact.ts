/**
 * Запрещает у `T` ключи сверх `Shape`.
 *
 * Обычная excess-property-check не срабатывает, когда `T` выводится как
 * generic type argument (а не проверяется напрямую как fresh object
 * literal) — `T extends Record<string, Shape>` при этом структурная
 * проверка, лишние поля ей не мешают. `Exact` требует `never` на месте
 * каждого ключа сверх `Shape`, так что лишнее поле становится обычной
 * ошибкой типов в точке использования.
 *
 * Ключи нормализуются шаблонным литералом (`${...}`) перед `Exclude`:
 * числовой литеральный ключ объекта (`{ 50: 'x' }` → `keyof` = число `50`)
 * иначе не совпадёт со строковым литералом из `Shape` (`'50'`) — `Exclude`
 * сравнивает типы буквально, и без нормализации числовые ключи всегда
 * считались бы «лишними».
 */
export type Exact<T, Shape> = Record<
	Exclude<`${Extract<keyof T, number | string>}`, `${Extract<keyof Shape, number | string>}`>,
	never
> &
	T;
