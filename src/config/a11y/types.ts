/**
 * Конфигурация доступности (a11y).
 *
 * Управляет HTML-атрибутами на `<html>`, которые активируют CSS-правила:
 * - `[no-motion]` — отключает все анимации и переходы
 * - `[no-transparency]` — заменяет полупрозрачные фоны непрозрачными
 *
 * @example
 * // Отключить анимации при старте:
 * a11y: {
 * 	motion: false,
 * }
 */
export type DefaultA11yConfig = {
	/**
	 * Разрешить анимации и переходы.
	 * Если `false` — атрибут `no-motion` устанавливается на `<html>` при старте.
	 */
	motion: boolean;

	/**
	 * Разрешить полупрозрачные фоны.
	 * Если `false` — атрибут `no-transparency` устанавливается на `<html>` при старте.
	 */
	transparency: boolean;
};

/**
 * Входная конфигурация a11y для плагина — все поля опциональны.
 */
export type ConfigA11y = Partial<DefaultA11yConfig>;
