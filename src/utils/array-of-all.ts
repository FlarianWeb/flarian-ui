/**
 * @name arrayOfAll
 * - Требует передать массив, ПОЛНОСТЬЮ покрывающий юнион `T` — не только
 *   «каждый элемент валиден» (это даёт и обычный `satisfies T[]`), но и
 *   «ни один член `T` не пропущен».
 * - `[T] extends [U[number]]` сравнивает юнион `T` целиком (квадратные скобки
 *   гасят distributive-поведение conditional type), иначе бы условие
 *   проверялось почленно и не ловило пропуски.
 * - Пропущенный ключ — ошибка компиляции с глухим `not assignable to 'never'`
 *   (без имени ключа, сверять список придётся глазами). Лишний/неверный
 *   ключ — обычная точная ошибка `keyof T`. Дубликаты не ловятся.
 */
export const arrayOfAll =
	<T extends string>() =>
	<U extends readonly T[]>(array: ([T] extends [U[number]] ? unknown : never) & U): U =>
		array;
